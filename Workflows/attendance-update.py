#!/usr/bin/env python3
"""Weekly adult attendance store — see Workflows/attendance-pull.md.

Canonical data: Trackers/Attendance-Data.csv (one row per Sunday x service time).
Rendered view:  Trackers/Attendance.md (regenerated every run, never hand-edited).

  python3 Workflows/attendance-update.py stale                 # exit 1 if a Sunday is missing
  python3 Workflows/attendance-update.py import FILE --source S # merge rows (TSV/CSV/JSON), then render
  python3 Workflows/attendance-update.py render                 # rebuild Attendance.md only

Import accepts rows of (date, value, service) as TSV/CSV, or a JSON list of
objects with keys date/value/service (Rock's MetricValue JSON: MetricValueDateTime,
YValue, and a partition label). Dates are snapped to the Sunday on or before,
because volunteers sometimes enter Sunday-night counts on Monday (Rock shows the
10/4/2026 6 PM count under 10/5).
"""
import csv, json, sys, re
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

VAULT = Path(__file__).resolve().parent.parent
DATA = VAULT / "Trackers" / "Attendance-Data.csv"
VIEW = VAULT / "Trackers" / "Attendance.md"
FIELDS = ["sunday", "service", "value", "source", "pulled"]
LAUNCH = date(2026, 9, 20)  # first Sunday Night service
REGULAR = ["9:00am", "10:15am", "11:30am", "6:00pm"]


def today():
    return datetime.now(ZoneInfo("America/New_York")).date()


def snap(d):  # Sunday on or before
    return d - timedelta(days=(d.weekday() + 1) % 7)


def norm_service(s):
    s = s.replace("Ballston Quarter and", "").replace("Sunday", "").strip().lower().replace(" ", "")
    m = re.match(r"0?(\d{1,2}):(\d{2})(am|pm)", s)
    return f"{int(m.group(1))}:{m.group(2)}{m.group(3)}" if m else s


def parse_date(s):
    s = s.strip()[:10] if "T" in s else s.strip()
    for fmt in ("%m/%d/%Y", "%Y-%m-%d"):
        try:
            return datetime.strptime(s, fmt).date()
        except ValueError:
            pass
    raise ValueError(f"bad date {s!r}")


def load():
    if not DATA.exists():
        return {}
    with DATA.open() as f:
        return {(r["sunday"], r["service"]): r for r in csv.DictReader(f)}


def save(rows):
    with DATA.open("w", newline="") as f:
        w = csv.DictWriter(f, FIELDS)
        w.writeheader()
        for k in sorted(rows, key=lambda k: (k[0], REGULAR.index(k[1]) if k[1] in REGULAR else 9, k[1])):
            w.writerow(rows[k])


def read_input(path):
    text = Path(path).read_text()
    out = []
    if text.lstrip().startswith("["):
        for o in json.loads(text):
            d = o.get("date") or o.get("MetricValueDateTime")
            v = o.get("value", o.get("YValue"))
            s = o.get("service") or o.get("partition") or o.get("SeriesName") or ""
            out.append((d, v, s))
    else:
        delim = "\t" if "\t" in text else ","
        for row in csv.reader(text.splitlines(), delimiter=delim):
            if len(row) >= 3 and re.match(r"\d", row[0]):
                out.append((row[0], row[1], row[2]))
    return out


def cmd_import(path, source):
    rows = load()
    pulled = today().isoformat()
    added = changed = 0
    for d, v, s in read_input(path):
        key = (snap(parse_date(d)).isoformat(), norm_service(s))
        val = str(int(float(v)))
        old = rows.get(key)
        if old and old["value"] == val:
            continue
        if old:
            changed += 1
            print(f"changed {key[0]} {key[1]}: {old['value']} -> {val}")
        else:
            added += 1
        rows[key] = {"sunday": key[0], "service": key[1], "value": val, "source": source, "pulled": pulled}
    save(rows)
    print(f"import: {added} added, {changed} changed, {len(rows)} rows total")
    render(rows)


def latest_sunday_with_data(rows):
    ds = [k[0] for k, r in rows.items() if r["value"] not in ("", "0")]
    return max(ds) if ds else None


def cmd_stale():
    rows = load()
    t = today()
    # counts for Sunday X are expected in Rock by Monday; on Sunday itself, expect the previous week
    expect = snap(t - timedelta(days=1)).isoformat()
    last = latest_sunday_with_data(rows)
    if last is None or last < expect:
        print(f"STALE: latest Sunday in store {last}, expected {expect} — pull from Rock")
        sys.exit(1)
    print(f"fresh: latest Sunday {last}")


def render(rows=None):
    rows = rows if rows is not None else load()
    by = {}
    for (d, s), r in rows.items():
        by.setdefault(d, {})[s] = int(r["value"])
    sundays = sorted(by)
    now = datetime.now(ZoneInfo("America/New_York")).strftime("%Y-%m-%d %H:%M")
    L = ["# 📈 Attendance", "",
         "**Generated by `Workflows/attendance-update.py` from [[Trackers/Attendance-Data.csv]] — never hand-edited.** "
         "Procedure: [[Workflows/attendance-pull]]. Source: Rock › Reporting › Metrics (adult attendance, Ballston Quarter), "
         "https://trygrace.rockcloud.com/reporting/metrics?MetricCategoryId=65&ExpandedIds=C193", "",
         f"generated: {now} ET · latest Sunday: {latest_sunday_with_data(rows)} · {len(sundays)} Sundays on file", ""]

    # Sunday Night since launch
    sn = [(d, by[d].get("6:00pm")) for d in sundays if d >= LAUNCH.isoformat()]
    L += ["## Sunday Night (6:00 PM) since launch", "",
          "| Sunday | 6 PM | 4-wk avg | AM total | 6 PM share |", "|---|---|---|---|---|"]
    vals = []
    for d, v in sn:
        am = sum(by[d].get(s, 0) for s in REGULAR[:3])
        if v is not None:
            vals.append(v)
        avg = round(sum(vals[-4:]) / len(vals[-4:])) if vals else ""
        share = f"{v / (am + v):.0%}" if v is not None and am else ""
        L.append(f"| {d} | {v if v is not None else '—'} | {avg} | {am or '—'} | {share} |")
    L.append("")

    # last 12 weeks, all services
    L += ["## Last 12 Sundays, all services", "",
          "| Sunday | 9:00 | 10:15 | 11:30 | 6:00 PM | Total | Same Sunday last year (AM) |", "|---|---|---|---|---|---|---|"]
    for d in sundays[-12:]:
        row = by[d]
        if not any(s in row for s in REGULAR):  # special-schedule weeks (e.g. Easter)
            L.append(f"| {d} | special schedule: " + ", ".join(f"{k} {v}" for k, v in row.items()) + f" | | | | {sum(row.values())} | |")
            continue
        cells = [str(row[s]) if s in row else "—" for s in REGULAR]
        ly = (date.fromisoformat(d) - timedelta(weeks=52)).isoformat()
        ly_am = sum(by.get(ly, {}).get(s, 0) for s in REGULAR[:3]) or "—"
        L.append(f"| {d} | " + " | ".join(cells) + f" | {sum(row.values())} | {ly_am} |")
    L += ["", "> Zeros are Sundays Rock recorded as no service (e.g. snow, holiday). Special-schedule Sundays (Easter 4/5/2026: 8:30/9:45/11:00/12:15) are kept as their own service times.", ""]
    VIEW.write_text("\n".join(L))
    print(f"rendered {VIEW.relative_to(VAULT)}")


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a:
        print(__doc__); sys.exit(2)
    if a[0] == "stale":
        cmd_stale()
    elif a[0] == "render":
        render()
    elif a[0] == "import" and len(a) >= 2:
        src = a[a.index("--source") + 1] if "--source" in a else "manual"
        cmd_import(a[1], src)
    else:
        print(__doc__); sys.exit(2)
